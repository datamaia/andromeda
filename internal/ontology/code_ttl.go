// pkgKey is a stable, non-empty key for a package directory ("(root)" for the module root).
func pkgKey(dir string) string {
	if dir == "" {
		return "(root)"
	}
	return dir
}

func pkgIRI(dir string) string { return "<pkg/" + iriEscape(pkgKey(dir)) + ">" }
func codeTypeIRI(dir, name string) string {
	return "<type/" + iriEscape(pkgKey(dir)) + "/" + iriEscape(name) + ">"
}
func codeFuncIRI(dir, localID string) string {
	return "<func/" + iriEscape(pkgKey(dir)) + "/" + iriEscape(localID) + ">"
}

// joinList renders a comma-separated Turtle object list.
func joinList(items []string) string {
	out := ""
	for i, s := range items {
		if i > 0 {
			out += " , "
		}
		out += s
	}
	return out
}
